#!/usr/bin/env bash
# Recover a HOM downsampling experiment without creating overlapping Nextflow
# controllers. Submit a single task-index-matched array with concurrency=1.
# Round 1 and Round 2 execute sequentially within the same array element.
# Defaults intentionally favor YCRC submission-rate safety over throughput.
#
# Examples (run from calling checkout):
#   HOM_CONSENSUS_MIN_DP=100 bash scripts/resume_hom_downsampling_throttled.sh --dry-run
#   HOM_CONSENSUS_MIN_DP=100 bash scripts/resume_hom_downsampling_throttled.sh
#   unset HOM_CONSENSUS_MIN_DP
#   bash scripts/resume_hom_downsampling_throttled.sh
#
# An array task can be rerun individually with sbatch --array=NN ... --worker.
set -euo pipefail
SELF="${BASH_SOURCE[0]}"
SCRIPT_DIR="$(cd "$(dirname "$SELF")" && pwd)"
CALL_REPO="${HOM_CALL_REPO:-$(cd "$SCRIPT_DIR/.." && pwd)}"
ANALYSIS_ROOT="${HOM_ANALYSIS_ROOT:-/vast/palmer/scratch/lake_nicole/lt692/primate_mtDNA_analysis_coverage_only}"
BASE="$ANALYSIS_ROOT/results/qc_coverage_only/downsampling_pilot"
MANIFEST="$BASE/candidate_downsampling_jobs.tsv"
PARTITION="${HOM_SLURM_PARTITION:-ycga}"
NEXTFLOW_MODULE="${NEXTFLOW_MODULE:-Nextflow/24.04.2}"
RATE="${HOM_NF_SUBMIT_RATE:-24/h}"
QUEUE_SIZE="${HOM_NF_QUEUE_SIZE:-2}"
COOLDOWN="${HOM_RETRY_COOLDOWN_SECONDS:-1200}"
[[ "$RATE" =~ ^[1-9][0-9]*/h$ ]] || { echo "ERROR: bad HOM_NF_SUBMIT_RATE=$RATE" >&2; exit 2; }
[[ "$QUEUE_SIZE" =~ ^[1-9][0-9]*$ ]] || { echo "ERROR: bad HOM_NF_QUEUE_SIZE=$QUEUE_SIZE" >&2; exit 2; }
[[ "$COOLDOWN" =~ ^[0-9]+$ ]] || { echo "ERROR: bad HOM_RETRY_COOLDOWN_SECONDS=$COOLDOWN" >&2; exit 2; }
[[ -s "$MANIFEST" ]] || { echo "ERROR: manifest missing: $MANIFEST" >&2; exit 2; }
N=$(( $(wc -l < "$MANIFEST") - 1 ))
[[ "$N" -gt 0 ]] || { echo "ERROR: empty manifest" >&2; exit 2; }
if [[ "${1:-}" == "--worker" ]]; then
    TASK="${SLURM_ARRAY_TASK_ID:?Requires Slurm array task}"
    [[ "$TASK" =~ ^[0-9]+$ ]] || exit 2
    read -r SAMPLE DEPTH SEED < <(awk -F '\t' -v idx="$TASK" 'NR==idx+1 {print $1,$6,$7;exit}' "$MANIFEST")
    [[ -n "${SAMPLE:-}" && "$DEPTH" =~ ^[0-9]+$ && "$SEED" =~ ^[0-9]+$ ]] || { echo "ERROR: invalid manifest item $TASK" >&2; exit 2; }
    case "$DEPTH" in 30) ADAPT_DP=10;; 50) ADAPT_DP=20;; 100) ADAPT_DP=30;; *) echo "Unsupported depth: $DEPTH" >&2; exit 2;; esac
    CDP="${HOM_CONSENSUS_MIN_DP:-$ADAPT_DP}"
    export HOM_CALL_REPO="$CALL_REPO" HOM_ANALYSIS_ROOT="$ANALYSIS_ROOT" NEXTFLOW_MODULE
    # Each experimental condition has independent workspace and published outputs.
    R1="$BASE/variant_calling_pilot/ds${DEPTH}x_seed${SEED}_cdp${CDP}/round1/$SAMPLE"
    R2="$BASE/variant_calling_pilot/ds${DEPTH}x_seed${SEED}_cdp${CDP}/round2/$SAMPLE"
    R1MT="$R1/round_1/mtdna_variant_calling"
    R1NUMT="$R1/round_1/numt_decoy_variant_calling/$SAMPLE.numt_decoy.pass.split.vcf.gz"
    R2VCF="$R2/round_2_variant_calling_original_coords/$SAMPLE.round2.original_coords.clean.final.split.vcf.gz"
    R2COV="$R2/round_2_variant_calling_original_coords/$SAMPLE.round2.original_coords.per_base_coverage.tsv"
    R2MT="$R2/round_2/mtcn/$SAMPLE.round2.mtcn.tsv"
    DS="$BASE/candidate_downsampled/$SAMPLE/$SAMPLE.candidate.ds${DEPTH}x.seed${SEED}.bam"
    echo "TASK=$TASK SAMPLE=$SAMPLE DEPTH=$DEPTH SEED=$SEED CDP=$CDP START=$(date -Is)"
    complete_r2() {
        [[ -s "$R2VCF" && -s "$R2VCF.tbi" && -s "$R2COV" && -s "$R2MT" ]]
    }
    complete_r1() {
        [[ -s "$R1NUMT" && -d "$R1MT" ]] && \
          [[ -n "$(find "$R1MT" -type f -name "$SAMPLE.numt_decoy.clean.final.split.vcf" -size +0c -print -quit)" ]]
    }
    if complete_r2; then
        echo "SKIP: Round2 complete ($SAMPLE ds${DEPTH}x seed$SEED cdp$CDP)"
        exit 0
    fi
    # Downsampling files are reused, never regenerated by this script.
    [[ -s "$DS" && -s "$DS.bai" ]] || { echo "ERROR: missing downsample BAM/index: $DS" >&2; exit 1; }
    # The trap also runs when nested Nextflow fails, to avoid rapid submission
    # of subsequent array tasks while YCRC's rolling-hour limit is saturated.
    trap 'rc=$?; echo "COOLDOWN ${COOLDOWN}s after task $TASK (rc=$rc)"; sleep "$COOLDOWN"; exit "$rc"' EXIT
    if complete_r1; then
        echo "SKIP: Round1 complete"
    else
        echo "RUN: Round1 with Nextflow -resume"
        bash "$CALL_REPO/scripts/launch_hom_downsampling_round1.sh" "$SAMPLE" "$DEPTH" "$SEED"
        complete_r1 || { echo "ERROR: Round1 ended without required files" >&2; exit 1; }
    fi
    if ! complete_r2; then
        echo "RUN: Round2 with Nextflow -resume"
        bash "$CALL_REPO/scripts/launch_hom_downsampling_round2.sh" "$SAMPLE" "$DEPTH" "$SEED"
        complete_r2 || { echo "ERROR: Round2 ended without required files" >&2; exit 1; }
    fi
    echo "SUCCESS: $SAMPLE ds${DEPTH}x seed$SEED cdp$CDP FINISH=$(date -Is)"
    exit 0
fi
[[ "${1:-}" == "" || "${1:-}" == "--dry-run" ]] || { echo "Usage: $0 [--dry-run|--worker]" >&2; exit 2; }
# Override only this pilot's Nextflow submission rate; do not change the
# production nextflow_mcc.config. Both launchers read this environment variable.
mkdir -p "$BASE/logs" "$BASE/pilot_config"
THROTTLE_CONFIG="$BASE/pilot_config/hom_nextflow_throttle.config"
cat > "$THROTTLE_CONFIG" <<EOF
executor {
    queueSize = $QUEUE_SIZE
    submitRateLimit = '$RATE'
}
EOF
export HOM_NF_EXTRA_CONFIG="$THROTTLE_CONFIG"
export HOM_CALL_REPO="$CALL_REPO" HOM_ANALYSIS_ROOT="$ANALYSIS_ROOT" NEXTFLOW_MODULE
echo "Recovery: $N manifest trials; one controller at a time; sequential Round1 -> Round2."
echo "Nextflow throttle=$RATE queueSize=$QUEUE_SIZE; cooldown after each run=${COOLDOWN}s"
echo "DP mode: ${HOM_CONSENSUS_MIN_DP:-adaptive (30:10, 50:20, 100:30)}"
echo "Config: $THROTTLE_CONFIG"
if [[ "${1:-}" == "--dry-run" ]]; then
    echo "DRY RUN: no job submitted."
    exit 0
fi
# A single array (rather than separate round arrays) prevents cross-stage
# overlap; array%1 ensures at most one controller among these trials.
JOB="$(sbatch --parsable --partition="$PARTITION" --array="1-${N}%1" \
  --job-name=hom_safe_resume --cpus-per-task=2 --mem=8G --time=24:00:00 \
  --output="$BASE/logs/hom_safe_resume_%A_%a.out" \
  --error="$BASE/logs/hom_safe_resume_%A_%a.err" \
  --export=ALL,HOM_CALL_REPO="$CALL_REPO",HOM_ANALYSIS_ROOT="$ANALYSIS_ROOT",NEXTFLOW_MODULE="$NEXTFLOW_MODULE",HOM_NF_EXTRA_CONFIG="$THROTTLE_CONFIG" \
  "$CALL_REPO/scripts/resume_hom_downsampling_throttled.sh" --worker)"
JOB="${JOB%%;*}"
echo "Submitted recovery array: $JOB"
printf 'job_id\tmode\trate\tqueue_size\tcooldown\n%s\t%s\t%s\t%s\t%s\n' \
  "$JOB" "${HOM_CONSENSUS_MIN_DP:-adaptive}" "$RATE" "$QUEUE_SIZE" "$COOLDOWN" \
  >> "$BASE/hom_safe_resume_jobs.tsv"
echo "Monitor: squeue -j $JOB; sacct -j $JOB -X"
